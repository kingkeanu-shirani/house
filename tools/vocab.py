"""The question and report vocabulary (house_sim/data/vocab/*.json): check it, print it, or write its tables.

usage: python tools/vocab.py [--check] [--markdown [OUT]] [--json OUT] [--words CATEGORY]

  (no option)     a summary: files, counts per section, issues per class
  --check         lint the files: a word naming two things in one table (aspects, details, issues, states), an
                  issue with an unknown class, a unit alias naming an unknown unit, a quantity without its canonical
                  unit, a severity alias naming an unknown severity, a category class list naming an unknown class,
                  a synonym whose target is itself a synonym; exit status 1 on any problem
  --markdown      the vocabulary tables of docs/DIALOGUE.md (aspects, details, issues by class, states, quantities and
                  units, severities, synonyms), so the docs and the data cannot drift; to OUT or stdout
  --json OUT      the merged vocabulary as JSON (without the lookup indexes)
  --words CAT     the issue words a report suggests for an entity category or issue class (reports.issue_words)

Loading is timed (budget 20 ms per process, TIER1_SWEEP 20).
"""
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def load():
    from house_sim.kernel import dialogue
    t0 = time.perf_counter()
    vocab = dialogue.load_vocabulary()
    return vocab, (time.perf_counter() - t0) * 1000.0


def problems(vocab):
    out = list(vocab["_index"]["problems"])
    classes = set(vocab["issue_classes"])
    for category, listed in sorted(vocab["category_classes"].items()):
        for cls in listed:
            if cls not in classes:
                out.append("category_classes.{} names unknown class {!r}".format(category, cls))
    synonyms = vocab["synonyms"]
    for word, target in sorted(synonyms.items()):
        if target in synonyms:
            out.append("synonym {!r} -> {!r} is itself a synonym (chains are not followed)".format(word, target))
        if word == target:
            out.append("synonym {!r} maps to itself".format(word))
    for name, spec in sorted(vocab["issues"].items()):
        for item in (spec or {}).get("evidence") or []:
            if not isinstance(item, dict) or not (item.get("field") or item.get("notice")):
                out.append("issue {} has an evidence entry without field or notice".format(name))
    for name, spec in sorted(vocab["states"].items()):
        opposite = (spec or {}).get("opposite")
        if opposite is not None and opposite not in vocab["states"]:
            out.append("state {} names unknown opposite {!r}".format(name, opposite))
    for region, row in sorted(vocab["household_units"].items()):
        for quantity, unit in sorted(row.items()):
            units = (vocab["quantities"].get(quantity) or {}).get("units") or {}
            if unit not in units:
                out.append("household_units.{}.{} names unknown unit {!r}".format(region, quantity, unit))
    for aspect in vocab["aspects"]:
        if aspect not in vocab["_index"]["aspects"]:
            out.append("aspect {} is not indexed".format(aspect))
    return out


def _cell(value):
    return str(value).replace("|", "/")


def markdown(vocab):
    from house_sim.kernel import reports
    lines = ["<!-- generated by python tools/vocab.py --markdown from house_sim/data/vocab/*.json ({}); do not edit "
             "by hand -->".format(", ".join(vocab["sources"])), ""]
    lines += ["### Aspects", "", "| aspect | the robot wants to know | also accepted |", "|---|---|---|"]
    for name, spec in vocab["aspects"].items():
        lines.append("| `{}` | {} | {} |".format(name, _cell(spec.get("doc", "")),
                                                 ", ".join(spec.get("synonyms") or []) or "-"))
    for name, spec in vocab["requests"].items():
        lines.append("| `{}` (a request) | {} | {} |".format(name, _cell(spec.get("doc", "")),
                                                               ", ".join(spec.get("synonyms") or []) or "-"))
    lines += ["", "### Details (preference slots and other details)", "", "| detail | also accepted |", "|---|---|"]
    for name, spec in vocab["details"].items():
        lines.append("| `{}` | {} |".format(name, ", ".join((spec or {}).get("synonyms") or []) or "-"))
    lines += ["", "### Report issues", "", "| class | issue | also accepted | evidence |", "|---|---|---|---|"]
    for cls in vocab["issue_classes"]:
        for name in reports.issue_words(cls):
            spec = vocab["issues"][name]
            evidence = ", ".join(("field " + e["field"] + (" (near)" if e.get("near") else "")) if e.get("field")
                                 else "notice " + str(e.get("notice")) for e in spec.get("evidence") or [])
            lines.append("| {} | `{}` | {} | {} |".format(cls, name, ", ".join(spec.get("synonyms") or []) or "-",
                                                         evidence or "-"))
    lines += ["", "### Report states", "", "| state | also accepted | opposite |", "|---|---|---|"]
    for name, spec in vocab["states"].items():
        lines.append("| `{}` | {} | {} |".format(name, ", ".join(spec.get("synonyms") or []) or "-",
                                                 spec.get("opposite") or "-"))
    lines += ["", "### Quantities and units", "", "| quantity | canonical | units (canonical = value x a + b) | also "
              "accepted |", "|---|---|---|---|"]
    for name, spec in vocab["quantities"].items():
        units = ", ".join("{} [{:g}, {:g}]".format(u, ab[0], ab[1]) for u, ab in spec["units"].items())
        aliases = ", ".join(sorted(spec.get("aliases") or {}))
        lines.append("| `{}` | {} | {} | {} |".format(name, spec["canonical"], units, aliases or "-"))
    lines += ["", "### Severities", "", "Ordered: " + " < ".join("`{}`".format(s) for s in vocab["severities"]) + ".",
              "Also accepted: " + ", ".join("{} = {}".format(k, v) for k, v in vocab["severity_aliases"].items()) + ".",
              "", "### Word synonyms (subjects of questions)", "", "| word | means |", "|---|---|"]
    for word, target in sorted(vocab["synonyms"].items()):
        lines.append("| {} | {} |".format(word.replace("_", " "), target.replace("_", " ")))
    lines += ["", "Stop words (ignored in subjects): " + ", ".join(vocab["stopwords"]) + ".", ""]
    return "\n".join(lines)


def main(argv):
    vocab, ms = load()
    if "--check" in argv:
        found = problems(vocab)
        for item in found:
            print("problem:", item)
        print("vocabulary {}: {} problem(s), loaded in {:.1f} ms".format(", ".join(vocab["sources"]), len(found), ms))
        return 1 if found else 0
    if "--markdown" in argv:
        text = markdown(vocab)
        i = argv.index("--markdown")
        out = argv[i + 1] if i + 1 < len(argv) and not argv[i + 1].startswith("--") else None
        if out:
            with open(out, "w", encoding="utf-8", newline="\n") as f:     # Path.write_text(newline=) is 3.10+
                f.write(text)
        else:
            sys.stdout.write(text)
        return 0
    if "--json" in argv:
        out = argv[argv.index("--json") + 1]
        data = {k: v for k, v in vocab.items() if not k.startswith("_")}
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(data, indent=1, sort_keys=True))
        return 0
    if "--words" in argv:
        from house_sim.kernel import reports
        print(", ".join(reports.issue_words(argv[argv.index("--words") + 1])))
        return 0
    print("vocabulary files: {} (loaded in {:.1f} ms)".format(", ".join(vocab["sources"]), ms))
    for section in ("aspects", "requests", "details", "synonyms", "issues", "states", "quantities", "severity_aliases",
                    "category_classes", "not_understood", "household_units"):
        print("  {:18s} {:4d}".format(section, len(vocab[section])))
    by_class = {}
    for name, spec in vocab["issues"].items():
        by_class.setdefault(spec.get("class"), []).append(name)
    for cls in vocab["issue_classes"]:
        print("  issues/{:11s} {:4d}".format(cls, len(by_class.get(cls, []))))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
